"""Example-guided room hypotheses with mirrored/rotated, two-way ink checks.

This is a local drawing matcher, not a semantic room classifier. Even a reviewed
example transfers a proposal, never its approval or completeness status.
"""
from __future__ import annotations

import time
import numpy as np
from scipy import ndimage, signal

VERSION = 'two-way-room-repetition-v1'
FIXED = {'maximum_pixels': 5_000_000, 'maximum_candidates': 240, 'maximum_results': 80,
         'seconds': 45, 'tolerance': 1, 'boundary_band': 3, 'minimum_ink': 32,
         'recall': .90, 'precision': .82, 'boundary_recall': .92,
         'minimum_room_pixels': 100, 'minimum_side': 10, 'overlap': .25}


def transform(array, turn, mirror):
    return np.rot90(np.fliplr(array) if mirror else array, turn).copy()


def proposals(ink, example, source_kind):
    """Input is only source ink and ONE explicit example mask. No corpus truth.

    source_kind records whether the example was human reviewed or is an exposed
    development hypothesis. Caller must bind both arrays to the same source hash.
    """
    start = time.monotonic()
    ink, example = np.asarray(ink), np.asarray(example)
    if (ink.dtype != bool or example.dtype != bool or ink.ndim != 2 or ink.shape != example.shape
            or ink.size > FIXED['maximum_pixels'] or source_kind not in {'human-reviewed', 'development-hypothesis'}):
        raise ValueError('Expected bounded same-source boolean ink and one example')
    _, n = ndimage.label(example)
    if n != 1 or example.sum() < FIXED['minimum_room_pixels']:
        raise ValueError('Example must be one substantial connected room; holes are allowed')
    ys, xs = np.where(example)
    pad = FIXED['boundary_band'] + 2
    y0, y1, x0, x1 = ys.min()-pad, ys.max()+pad+1, xs.min()-pad, xs.max()+pad+1
    if y0 < 0 or x0 < 0 or y1 > ink.shape[0] or x1 > ink.shape[1] or min(y1-y0, x1-x0) < FIXED['minimum_side']:
        raise ValueError('Example needs complete surrounding source context')
    template, shape = ink[y0:y1, x0:x1].copy(), example[y0:y1, x0:x1].copy()
    context = ndimage.binary_dilation(shape, iterations=FIXED['boundary_band'])
    band = context & ~ndimage.binary_erosion(shape, iterations=FIXED['boundary_band'])
    template &= context
    if template.sum() < FIXED['minimum_ink'] or (template & band).sum() < FIXED['minimum_ink']:
        raise ValueError('Example lacks surrounding drawing evidence')
    target_near = ndimage.maximum_filter(ink, size=2*FIXED['tolerance']+1).astype(np.float32)
    results, examined, rejected = [], 0, {'recall': 0, 'precision': 0, 'boundary': 0, 'new_partition': 0}
    for mirror in (False, True):
        for turn in range(4):
            if time.monotonic() - start > FIXED['seconds']:
                raise RuntimeError('Repeat-search time budget; no successful partial result')
            t, room, scope, rim = [transform(a, turn, mirror) for a in (template, shape, context, band)]
            h, w = t.shape
            if h > ink.shape[0] or w > ink.shape[1]:
                continue
            # Translation candidates are generated by positive-ink support only.
            # Fine checks below also penalize contradictory walls and extra ink.
            scores = signal.fftconvolve(target_near, t[::-1, ::-1].astype(np.float32), mode='valid') / t.sum()
            maxima = (scores >= FIXED['recall']-1e-5) & (scores == ndimage.maximum_filter(scores, size=5))
            coords = np.argwhere(maxima)
            order = sorted(coords.tolist(), key=lambda p: (-float(scores[tuple(p)]), p[0], p[1]))
            # Fail instead of returning an arbitrary truncated set of hypotheses.
            if examined + len(order) > FIXED['maximum_candidates']:
                raise RuntimeError('Repeat-search candidate budget; ambiguous/repetitive drawing')
            near_template = ndimage.maximum_filter(t, size=2*FIXED['tolerance']+1)
            interior = ndimage.binary_erosion(room, iterations=FIXED['boundary_band'])
            for y, x in order:
                examined += 1
                candidate = ink[y:y+h, x:x+w] & scope
                nearby = target_near[y:y+h, x:x+w].astype(bool)
                recall = float(nearby[t].mean())
                precision = float(near_template[candidate].mean()) if candidate.any() else 0.
                boundary = float(nearby[t & rim].mean())
                if recall < FIXED['recall']:
                    rejected['recall'] += 1
                    continue
                if precision < FIXED['precision']:
                    rejected['precision'] += 1
                    continue
                if boundary < FIXED['boundary_recall']:
                    rejected['boundary'] += 1
                    continue
                # A new substantial interior stroke can divide the destination:
                # a lookalike apartment or room must not swallow that extra wall.
                unexpected = candidate & interior & ~near_template
                parts, count = ndimage.label(unexpected, np.ones((3, 3), bool))
                contradiction = False
                for region in ndimage.find_objects(parts, max_label=count):
                    if region and max(region[0].stop-region[0].start, region[1].stop-region[1].start) >= max(8, .35*min(h, w)):
                        contradiction = True
                        break
                if contradiction:
                    rejected['new_partition'] += 1
                    continue
                if (example[y:y+h, x:x+w] & room).sum() / room.sum() > FIXED['overlap']:
                    continue
                results.append({'x': int(x), 'y': int(y), 'mask': room,
                                'quarter_turns_ccw': turn, 'mirror_x_before_rotation': mirror,
                                'ink_recall': recall, 'ink_precision': precision, 'boundary_recall': boundary,
                                'exact_support': float(candidate[t].mean()),
                                'score': min(recall, precision, boundary), 'requires_review': True,
                                'review_status': 'pending', 'example_kind': source_kind,
                                'score_is_calibrated_confidence': False})
    accepted = []
    for r in sorted(results, key=lambda r: (-r['score'], -r['exact_support'], r['y'], r['x'], r['mirror_x_before_rotation'], r['quarter_turns_ccw'])):
        duplicate = False
        for a in accepted:
            y0, x0 = max(a['y'], r['y']), max(a['x'], r['x'])
            y1 = min(a['y']+a['mask'].shape[0], r['y']+r['mask'].shape[0])
            x1 = min(a['x']+a['mask'].shape[1], r['x']+r['mask'].shape[1])
            if y1 <= y0 or x1 <= x0:
                continue
            intersection = (a['mask'][y0-a['y']:y1-a['y'], x0-a['x']:x1-a['x']] &
                            r['mask'][y0-r['y']:y1-r['y'], x0-r['x']:x1-r['x']]).sum()
            if intersection / min(a['mask'].sum(), r['mask'].sum()) > FIXED['overlap']:
                duplicate = True
                break
        if not duplicate:
            accepted.append(r)
    if len(accepted) > FIXED['maximum_results'] or time.monotonic()-start > FIXED['seconds']:
        raise RuntimeError('Repeat-search result/time budget')
    return accepted, {'version': VERSION, 'examined': examined, 'rejected': rejected,
                      'seconds': time.monotonic()-start, 'approved_for_production': False,
                      'limitations': 'Similar ink is not proof of identical room use or boundaries. Every copy needs independent review.'}
