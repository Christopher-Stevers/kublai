#!/usr/bin/env bash
set -euo pipefail
cd "$(dirname "$0")/.."
export PATH="$HOME/.cargo/bin:$PATH"
cargo build --locked --release --target wasm32-unknown-unknown --manifest-path native/geometry/Cargo.toml
wasm-bindgen native/geometry/target/wasm32-unknown-unknown/release/foreman_geometry.wasm --target web --out-dir src/lib/geometry-wasm --out-name geometry
# The bundler sees only JS; serve the versioned binary as a static asset.
mv src/lib/geometry-wasm/geometry_bg.wasm public/wasm/foreman-geometry-v1.wasm
rm src/lib/geometry-wasm/geometry_bg.wasm.d.ts
sed -i '1i// @ts-nocheck -- generated by wasm-bindgen; rebuild with scripts/build-geometry-wasm.sh' src/lib/geometry-wasm/geometry.js
sed -i "s@new URL('geometry_bg.wasm', import.meta.url)@'/wasm/foreman-geometry-v1.wasm'@" src/lib/geometry-wasm/geometry.js
